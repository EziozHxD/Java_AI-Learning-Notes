package com.Ezio.literal;

public class LiteralDemo1 {
    public static void main(String[] args) {
        // 输出野兽先辈的信息：田所浩二 24岁 男 学生

        // 1.输出野兽先辈的名字
        System.out.println("田所浩二");  // 字符串类型，用""括起来

        // 2.输出野兽先辈的年龄
        System.out.println(24);  // 整数/小数类型，直接写

        // 3.输出野兽先辈的性别
        System.out.println('男');  // 字符类型，用''括起来

        // 4.输出野兽先辈的职业
        System.out.println("是学生");  // 字符串类型，用""括起来
    }
}
