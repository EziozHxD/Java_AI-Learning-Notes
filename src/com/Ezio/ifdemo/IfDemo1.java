package com.Ezio.ifdemo;

public class IfDemo1 {
    public static void main(String[] args) {

        // 定义变量表示san值，当san值大于200的时候就会变成赛博精神病。
        int san = 277;
        if (san > 200) {
            System.out.println("你的san值是：" + san);
            System.out.println("你变成了赛博精神病");
        }
    }
}
